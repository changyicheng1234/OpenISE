# 虚拟地址和真实地址的D代表的是真实页中数据的偏移量，一页是128B，以字节为单位，那么D是7位
# D是7位，那么C是12-7=5位，A=16-7=9位，B=A=9位，TLB和页表的页框号均为C=5位
# 那么A代表的是某一页的虚拟地址，C是某一页的真实地址

# TLB大小没有说明，所以假设TLB可以存储4页（4个虚拟地址->物理地址的映射）
# 主存大小为4KB，块的大小为32B。那么主存有128块，4块一页，共有32页
# 假设页表可以存储32页（32个虚拟地址->物理地址的映射）

# cache的数据区大小为1KB，块大小为32B，所以共有32块，由于为两路组相连，每组2块，共16组
# 主存有128块， 所以128 / 16 = 8， 所以主存分属16组，每组可能的数据有8块， 那么cache属于8选2，由E确定组内序号
# E=8=2^3=3位，F=16=2^4=4位,G=32B/B=2^5=5位
# cache里有16行，主存序号/16 = 组相连组号， F确定cache里的第几行
# H和E比较，位数为3，如果对应上，对应数据就在cache，没对应，则数据在主存

