# TLB的格式为：有效位（1位） + 虚拟页号（9位） + 真实页号（5位） + 填充位（1位）
# 假设TLB有4行
# 假设此时TLB为空
TLB = []
# 页表的格式为：有效位（1位） + 虚拟页号（9位） + 真实页号（5位） + 填充位（1位）
# 页表32行，包含所有页的虚拟地址向真实地址的映射
table = []

vir = ''
real = ''
# 生产32个映射，此时的C包含了00000-11111共2^5=32个页的地址
for i in range(0, 32):
    vir = str(bin(i*16))[2:]
    while len(vir) < 9:
        vir = '0' + vir

    real = str(bin(i))[2:]
    while len(real) < 5:
        real = '0' + real

    if i % 10 == 1:
        TLB.append('1' + vir + real + '0')

    table.append('1' + vir + real + '0')

# 1、虚拟地址的对应页地址是否在TLB中
# 在 -> 读取TLB的中的物理地址，跳转到4
table_vir = []
for i in TLB:
    B.append(i[1: 0])
for i in table:
    table_vir.append(i[1: 10])

if A in B:
    C = TLB[B.index(A)][10: 15]
    print("虚拟地址和物理地址的转换在TLB查找")
# 不在 -> 访问页表
# 2、访问页表查找
elif A in table_vir:
    C = table[table_vir.index(A)][10: 15]
    print("虚拟地址和物理地址的转换在页表查找")
else:
    print("地址错误")

# 4、对应页数据是否在cache中
# 此时得到5位的C和7位的D，把这拆解为3位的E，4位的F，5位的G
# F确定组号， E进行标记对比， G进行地址寻址
# 在 -> 跳转6
E = C[0: 3]
F = C[3: 4] + D[0: 3]
G = D[3: 6]
data = ''

line = int(F)

if E == cache[line][0: 3] and cache[line][3] == '1':
    data = cache[line][4: 4 + 32 * 8]
    print("在cache中找到相关数据")
